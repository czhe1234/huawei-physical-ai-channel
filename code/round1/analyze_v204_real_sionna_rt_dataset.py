"""Evaluate project-style predictors on a real Sionna RT generated dataset.

This script reads the full frequency-domain H generated by
``generate_v204_real_sionna_rt_dataset.py`` and evaluates transferable
predictors on the held-out Sionna test subset.  It does not generate a
leaderboard submission.
"""

