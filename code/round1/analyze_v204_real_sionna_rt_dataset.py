VERSION = "v204_real_sionna_rt_dataset_evaluation"
OUT_DIR = PATHS.cache_dir(204)
REPORT_DIR = PATHS.version_report_dir(204)
VIS_DIR = PATHS.analysis / "visualizations" / "v204_real_sionna_rt_dataset"
METADATA = OUT_DIR / "v204_real_sionna_rt_dataset_metadata.json"
TRAIN_H = OUT_DIR / "v204_real_sionna_train_H.npy"
