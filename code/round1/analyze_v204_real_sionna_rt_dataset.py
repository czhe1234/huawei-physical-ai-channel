def total_power(h: np.ndarray) -> np.ndarray:
    return np.sum(np.abs(h) ** 2, axis=(1, 2, 3), dtype=np.float64).astype(np.float64)


def summarize(x: np.ndarray) -> dict[str, float | int]:
    y = np.asarray(x, dtype=np.float64)
    y = y[np.isfinite(y)]
    if len(y) == 0:
        return {"count": 0}
    return {
        "count": int(len(y)),
        "mean": float(np.mean(y)),
        "std": float(np.std(y)),
        "min": float(np.min(y)),
        "p10": float(np.quantile(y, 0.10)),
        "p50": float(np.quantile(y, 0.50)),
        "p90": float(np.quantile(y, 0.90)),
        "max": float(np.max(y)),
    }


def regression_metrics(y: np.ndarray, p: np.ndarray) -> dict[str, float | int]:
    y = np.asarray(y, dtype=np.float64)
    p = np.asarray(p, dtype=np.float64)
    err = p - y
    abs_err = np.abs(err)
    if len(y) < 2:
        return {"count": int(len(y))}
    ss_res = float(np.sum(err * err))
    ss_tot = float(np.sum((y - np.mean(y)) ** 2))
    return {
        "count": int(len(y)),
        "mae_log": float(np.mean(abs_err)),
        "rmse_log": float(np.sqrt(np.mean(err * err))),
        "bias_log": float(np.mean(err)),
        "p50_abs_log": float(np.quantile(abs_err, 0.50)),
        "p90_abs_log": float(np.quantile(abs_err, 0.90)),
        "r2": float(1.0 - ss_res / max(ss_tot, 1e-30)),
        "pearson": v203.safe_corr(y, p, "pearson"),
        "spearman": v203.safe_corr(y, p, "spearman"),
    }


def nmse_metrics(y: np.ndarray, p: np.ndarray, regimes: np.ndarray) -> dict[str, object]:
    err = np.abs(p - y) ** 2
    den = np.abs(y) ** 2
    out: dict[str, object] = {
        "overall": {
            "nmse": float(np.sum(err, dtype=np.float64) / max(float(np.sum(den, dtype=np.float64)), 1e-30)),
            "rmse_complex": float(np.sqrt(np.mean(err, dtype=np.float64))),
            "mean_true_power": float(np.mean(np.sum(den, axis=(1, 2, 3), dtype=np.float64))),
        }
    }
    for regime in ["clear", "light", "medium", "heavy"]:
        mask = regimes.astype(str) == regime
        if not np.any(mask):
            out[regime] = {"count": 0}
            continue
        out[regime] = {
            "count": int(np.sum(mask)),
            "nmse": float(np.sum(err[mask], dtype=np.float64) / max(float(np.sum(den[mask], dtype=np.float64)), 1e-30)),
        }
    return out


def effective_neighbor_indices(
    train_pos: np.ndarray,
    test_pos: np.ndarray,
    train_blocked: np.ndarray,
    test_blocked: np.ndarray,
    train_regimes: np.ndarray,
    test_regimes: np.ndarray,
    k: int,
) -> tuple[np.ndarray, np.ndarray]:
    dxy = np.linalg.norm(test_pos[:, None, :2] - train_pos[None, :, :2], axis=2)
    db = np.abs(test_blocked[:, None].astype(np.float32) - train_blocked[None, :].astype(np.float32))
    mismatch = (test_regimes[:, None] != train_regimes[None, :]).astype(np.float32)
    effective = dxy + 0.105 * db + 6.0 * mismatch
    k_eff = min(k, len(train_pos))
    idx = np.argpartition(effective, k_eff - 1, axis=1)[:, :k_eff]
    rows = np.arange(len(test_pos))[:, None]
    idx = idx[rows, np.argsort(effective[rows, idx], axis=1)]
    selected = effective[rows, idx]
    same = (test_regimes[:, None] == train_regimes[idx]).astype(np.float32)
    weights = np.exp(-selected / 18.0).astype(np.float32) * (0.48 + 0.52 * same)
    weights /= np.maximum(weights.sum(axis=1, keepdims=True), TINY)
    return idx.astype(np.int32), weights.astype(np.float32)


def complex_knn_predict(train_h: np.ndarray, idx: np.ndarray, weights: np.ndarray) -> np.ndarray:
    out = np.empty((len(idx), 256, 4, 192), dtype=np.complex64)
    for i in range(len(idx)):
        block = np.asarray(train_h[idx[i]], dtype=np.complex64)
        out[i] = np.sum(weights[i, :, None, None, None].astype(np.float32) * block, axis=0).astype(np.complex64)
        if (i + 1) % 10 == 0 or i + 1 == len(idx):
            print(f"complex knn {i + 1}/{len(idx)}", flush=True)
    return out


def fit_power_model(x_train: np.ndarray, y_train: np.ndarray, x_test: np.ndarray, seed: int) -> dict[str, np.ndarray]:
    models = {
        "extra": ExtraTreesRegressor(
            n_estimators=360,
            min_samples_leaf=3,
            max_features=0.82,
            random_state=seed,
            n_jobs=-1,
        ),
        "hgb": HistGradientBoostingRegressor(
            max_iter=320,
            learning_rate=0.045,
            max_leaf_nodes=31,
            min_samples_leaf=10,
            l2_regularization=0.035,
            random_state=seed,
        ),
    }
    preds: dict[str, np.ndarray] = {}
    for name, model in models.items():
        pipe = make_pipeline(RobustScaler(with_centering=True, with_scaling=True), model)
        pipe.fit(x_train, y_train)
        preds[name] = pipe.predict(x_test).astype(np.float32)
    preds["mean"] = np.mean(np.stack([preds["extra"], preds["hgb"]], axis=0), axis=0).astype(np.float32)
    preds["spread"] = np.abs(preds["extra"] - preds["hgb"]).astype(np.float32)
    return preds


def fit_nonzero_classifier(
    x_train: np.ndarray,
    y_train: np.ndarray,
    x_test: np.ndarray,
    y_test: np.ndarray,
    seed: int,
) -> tuple[np.ndarray, dict[str, float | int]]:
    clf = make_pipeline(
        RobustScaler(with_centering=True, with_scaling=True),
        ExtraTreesClassifier(
            n_estimators=400,
            min_samples_leaf=3,
            max_features=0.80,
            random_state=seed,
            n_jobs=-1,
            class_weight="balanced",
        ),
    )
    clf.fit(x_train, y_train)
    prob = clf.predict_proba(x_test)[:, 1].astype(np.float32)
    pred = (prob >= 0.5).astype(np.int32)
    precision, recall, f1, _ = precision_recall_fscore_support(
        y_test,
        pred,
        average="binary",
        zero_division=0,
    )
    metrics = {
        "auc": float(roc_auc_score(y_test, prob)) if len(np.unique(y_test)) == 2 else float("nan"),
        "average_precision": float(average_precision_score(y_test, prob)),
        "accuracy": float(accuracy_score(y_test, pred)),
        "precision": float(precision),
        "recall": float(recall),
        "f1": float(f1),
        "predicted_nonzero_count": int(np.sum(pred)),
        "true_nonzero_count": int(np.sum(y_test)),
    }
    return prob, metrics


def scale_to_log_power(h: np.ndarray, target_log_power: np.ndarray) -> np.ndarray:
    current = np.maximum(total_power(h), 1e-30)
    target = np.exp(target_log_power.astype(np.float64))
    scale = np.sqrt(target / current).astype(np.float32)
    return (h * scale[:, None, None, None]).astype(np.complex64)


def make_plots(report: dict[str, object], true_log: np.ndarray, pred_logs: dict[str, np.ndarray]) -> list[str]:
    VIS_DIR.mkdir(parents=True, exist_ok=True)
    paths: list[str] = []
    names = list(pred_logs.keys())
    rmse = [regression_metrics(true_log, pred_logs[name])["rmse_log"] for name in names]
    fig, ax = plt.subplots(figsize=(10, 4))
    ax.bar(np.arange(len(names)), rmse)
    ax.set_xticks(np.arange(len(names)))
    ax.set_xticklabels(names, rotation=25, ha="right")
    ax.set_ylabel("test log-power RMSE")
    ax.set_title("v204 real Sionna dataset: power predictor RMSE")
    fig.tight_layout()
    path = VIS_DIR / "v204_power_predictor_rmse.png"
    fig.savefig(path, dpi=160)
    plt.close(fig)
    paths.append(PATHS.relative(path))

    fig, ax = plt.subplots(figsize=(6, 6))
    for name in ["knn_log", "basic_model", "path_public_model", "path_material_model"]:
        ax.scatter(true_log, pred_logs[name], s=18, alpha=0.55, label=name)
    lo = float(np.quantile(true_log, 0.01))
    hi = float(np.quantile(true_log, 0.99))
    ax.plot([lo, hi], [lo, hi], color="black", linewidth=1)
    ax.set_xlabel("true Sionna test log power")
    ax.set_ylabel("predicted log power")
    ax.set_title("v204 real Sionna power predictions")
    ax.legend(fontsize=8)
    fig.tight_layout()
    path = VIS_DIR / "v204_power_prediction_scatter.png"
    fig.savefig(path, dpi=160)
    plt.close(fig)
    paths.append(PATHS.relative(path))
    report["plots"] = paths
    return paths


def main() -> None:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    if not METADATA.is_file():
        raise FileNotFoundError(METADATA)
    metadata = json.loads(METADATA.read_text(encoding="utf-8"))
    train_idx = np.asarray(metadata["train_indices"], dtype=np.int32)
    test_idx = np.asarray(metadata["test_indices"], dtype=np.int32)

    train_h = np.load(TRAIN_H, mmap_mode="r")
    test_h = np.load(TEST_H, mmap_mode="r")
    if train_h.shape[1:] != (256, 4, 192) or test_h.shape[1:] != (256, 4, 192):
        raise ValueError(f"Unexpected H shapes: {train_h.shape}, {test_h.shape}")
    train_power = total_power(np.asarray(train_h))
    test_power = total_power(np.asarray(test_h))
    train_log = np.log(np.maximum(train_power, 1e-30)).astype(np.float32)
    test_log = np.log(np.maximum(test_power, 1e-30)).astype(np.float32)

    inputs = v203.load_inputs()
    train_pos = inputs.train_pos[train_idx]
    test_pos = inputs.test_pos[test_idx]
    train_blocked = inputs.train_blocked[train_idx]
    test_blocked = inputs.test_blocked[test_idx]
    train_regimes = inputs.train_regimes[train_idx]
    test_regimes = inputs.test_regimes[test_idx]

    idx16, w16 = effective_neighbor_indices(
        train_pos, test_pos, train_blocked, test_blocked, train_regimes, test_regimes, k=16
    )
    idx32, w32 = effective_neighbor_indices(
        train_pos, test_pos, train_blocked, test_blocked, train_regimes, test_regimes, k=32
    )
    knn_log16 = np.sum(w16 * train_log[idx16], axis=1).astype(np.float32)
    knn_log32 = np.sum(w32 * train_log[idx32], axis=1).astype(np.float32)

    x_basic_train = inputs.train_basic_features[train_idx]
    x_basic_test = inputs.test_basic_features[test_idx]
    x_path_public_train = np.concatenate(
        [inputs.train_basic_features[train_idx], inputs.train_path_features_public[train_idx]],
        axis=1,
    )
    x_path_public_test = np.concatenate(
        [inputs.test_basic_features[test_idx], inputs.test_path_features_public[test_idx]],
        axis=1,
    )
    x_path_material_train = np.concatenate(
        [inputs.train_basic_features[train_idx], inputs.train_path_features_material[train_idx]],
        axis=1,
    )
    x_path_material_test = np.concatenate(
        [inputs.test_basic_features[test_idx], inputs.test_path_features_material[test_idx]],
        axis=1,
    )
    basic_pred = fit_power_model(x_basic_train, train_log, x_basic_test, seed=2041)
    path_public_pred = fit_power_model(x_path_public_train, train_log, x_path_public_test, seed=2042)
    path_material_pred = fit_power_model(x_path_material_train, train_log, x_path_material_test, seed=2043)
    train_nonzero = (train_log > -60.0).astype(np.int32)
    test_nonzero = (test_log > -60.0).astype(np.int32)
    nonzero_classifiers: dict[str, dict[str, float | int]] = {}
    nonzero_prob: dict[str, np.ndarray] = {}
    for name, xtr, xte, seed in [
        ("basic", x_basic_train, x_basic_test, 2051),
        ("path_public", x_path_public_train, x_path_public_test, 2052),
        ("path_material", x_path_material_train, x_path_material_test, 2053),
    ]:
        prob, metrics = fit_nonzero_classifier(xtr, train_nonzero, xte, test_nonzero, seed)
        nonzero_prob[name] = prob
        nonzero_classifiers[name] = metrics
    path_public_nonzero_reg = fit_power_model(
        x_path_public_train[train_nonzero == 1],
        train_log[train_nonzero == 1],
        x_path_public_test,
        seed=2054,
    )
    gated_path_public_log = np.where(
        nonzero_prob["path_public"] >= 0.5,
        path_public_nonzero_reg["mean"],
        -69.0775528,
    ).astype(np.float32)

    print("building complex knn predictions", flush=True)
    pred_nn = np.asarray(train_h[idx16[:, 0]], dtype=np.complex64)
    pred_knn16 = complex_knn_predict(train_h, idx16, w16)
    pred_knn32 = complex_knn_predict(train_h, idx32, w32)
    pred_knn32_scale_knn = scale_to_log_power(pred_knn32, knn_log32)
    pred_knn32_scale_basic = scale_to_log_power(pred_knn32, basic_pred["mean"])
    pred_knn32_scale_path_public = scale_to_log_power(pred_knn32, path_public_pred["mean"])
    pred_knn32_scale_path_material = scale_to_log_power(pred_knn32, path_material_pred["mean"])
    pred_knn32_scale_gated_path_public = scale_to_log_power(pred_knn32, gated_path_public_log)
    pred_knn32_scale_oracle = scale_to_log_power(pred_knn32, test_log)

    true_test = np.asarray(test_h, dtype=np.complex64)
    complex_preds = {
        "nearest_neighbor": pred_nn,
        "complex_knn16": pred_knn16,
        "complex_knn32": pred_knn32,
        "knn32_scaled_to_knn_power": pred_knn32_scale_knn,
        "knn32_scaled_to_basic_power": pred_knn32_scale_basic,
        "knn32_scaled_to_path_public_power": pred_knn32_scale_path_public,
        "knn32_scaled_to_path_material_power": pred_knn32_scale_path_material,
        "knn32_scaled_to_gated_path_public_power": pred_knn32_scale_gated_path_public,
        "knn32_scaled_to_oracle_power": pred_knn32_scale_oracle,
    }
    complex_metrics = {name: nmse_metrics(true_test, pred, test_regimes) for name, pred in complex_preds.items()}

    power_preds = {
        "knn_log": knn_log32,
        "basic_model": basic_pred["mean"],
        "path_public_model": path_public_pred["mean"],
        "path_material_model": path_material_pred["mean"],
        "gated_path_public_model": gated_path_public_log,
    }
    power_metrics = {name: regression_metrics(test_log, pred) for name, pred in power_preds.items()}
    regime_power_metrics = {
        name: {
            regime: regression_metrics(test_log[test_regimes == regime], pred[test_regimes == regime])
            for regime in ["clear", "light", "medium", "heavy"]
            if np.any(test_regimes == regime)
        }
        for name, pred in power_preds.items()
    }

    report: dict[str, object] = {
        "method": VERSION,
        "status": "analysis_only_no_candidate",
        "source_dataset": PATHS.relative(METADATA),
        "train_shape": list(train_h.shape),
        "test_shape": list(test_h.shape),
        "train_power_summary": summarize(train_log),
        "test_power_summary": summarize(test_log),
        "train_regime_counts": metadata.get("train_regime_counts", {}),
        "test_regime_counts": metadata.get("test_regime_counts", {}),
        "power_metrics": power_metrics,
        "regime_power_metrics": regime_power_metrics,
        "nonzero_threshold_log_power": -60.0,
        "nonzero_classifier_metrics": nonzero_classifiers,
        "complex_nmse_metrics": complex_metrics,
        "interpretation": {
            "best_power_rmse": min((m["rmse_log"], name) for name, m in power_metrics.items()),
            "best_complex_nmse": min((m["overall"]["nmse"], name) for name, m in complex_metrics.items()),
            "oracle_power_scaled_nmse": complex_metrics["knn32_scaled_to_oracle_power"]["overall"]["nmse"],
            "path_power_scaled_nmse": complex_metrics["knn32_scaled_to_path_material_power"]["overall"]["nmse"],
            "gated_path_public_power_rmse": power_metrics["gated_path_public_model"]["rmse_log"],
            "gated_path_public_power_mae": power_metrics["gated_path_public_model"]["mae_log"],
        },
    }
    plot_paths = make_plots(report, test_log, power_preds)
    np.savez_compressed(
        PRED_OUT,
        test_log=test_log,
        train_log=train_log,
        knn_log=knn_log32,
        basic_model=basic_pred["mean"],
        path_public_model=path_public_pred["mean"],
        path_material_model=path_material_pred["mean"],
        gated_path_public_model=gated_path_public_log,
        path_public_nonzero_probability=nonzero_prob["path_public"],
        test_regimes=test_regimes.astype("U8"),
    )
    report["outputs"] = {
        "json": PATHS.relative(REPORT),
        "predictions": PATHS.relative(PRED_OUT),
        "plots": plot_paths,
    }
    REPORT.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps({"report": PATHS.relative(REPORT), "best_power": report["interpretation"]["best_power_rmse"], "best_complex": report["interpretation"]["best_complex_nmse"]}, indent=2))


if __name__ == "__main__":
    main()
